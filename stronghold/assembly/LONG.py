def assemble_genome(reads):
    reads = [r for r in reads if r]
    genome = reads.pop(0)

    while reads:
        found = False
        for i, r in enumerate(reads):
            min_overlap = len(r) // 2

            for k in range(len(r), min_overlap, -1):
                if genome.endswith(r[:k]):
                    genome = genome + r[k:]
                    reads.pop(i)
                    found = True
                    break
            if found:
                break

            for k in range(len(r), min_overlap, -1):
                if genome.startswith(r[-k:]):
                    genome = r[:-k] + genome
                    reads.pop(i)
                    found = True
                    break
            if found:
                break

    return genome


