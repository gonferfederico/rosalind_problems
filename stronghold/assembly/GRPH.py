def parse_fasta(fasta_text):
    records = {}
    current_label = None
    current_seq = []
    
    for line in fasta_text.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith(">"):
            if current_label:
                records[current_label] = "".join(current_seq)
            current_label = line[1:].strip()
            current_seq = []
        else:
            current_seq.append(line)
            
    if current_label:
        records[current_label] = "".join(current_seq)
        
    return records


def overlap_graph(fasta_text, k=3):
    dna_dict = parse_fasta(fasta_text)
    edges = []
    
    for id1, seq1 in dna_dict.items():
        suffix = seq1[-k:]
        for id2, seq2 in dna_dict.items():
            if id1 != id2 and suffix == seq2[:k]:
                edges.append(f"{id1} {id2}")
                
    return "\n".join(edges)

